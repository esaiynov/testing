/* 
1: for — график платежей. Покупатель оформил товар за 24 000 тг в рассрочку на 6 месяцев. Выведите в консоль номер каждого месяца, размер платежа и сумму, которая останется после него.
2: while — накопление на ноутбук. Через prompt() спросите цену ноутбука и сумму, которую студент откладывает каждый месяц. Выводите накопленную сумму после каждого месяца, пока денег не станет достаточно.
3: do...while — выбор оценки доставки. Через prompt() запрашивайте оценку от 1 до 5. Если введено число вне этого диапазона, спрашивайте снова. После правильного ввода покажите через alert(): «Спасибо! Ваша оценка: …». */


let оценка;
do {
    оценка = Number(window.prompt("Введите Цифру от 1 до 5"));
} while (оценка < 1 || оценка > 5);


console.log("Спасибо! Ваша оценка: " + оценка)

